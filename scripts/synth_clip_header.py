"""PlatformIO pre-build script: turns a recorded clip into the synthetic source table.

A SYNTHETIC build normally loops include/tick_tock_pcm.h. Building with
``-DTG_SYNTH_CLIP=<id>`` (an id from assets/synth_clips/clips.json) instead
generates ``synth_clip_pcm.h`` from ``assets/synth_clips/<id>.wav`` into the
build directory, puts that directory on the include path and defines
``TG_SYNTH_CLIP_NAME`` (shown as ``hello.source``, e.g. ``SYNTHETIC:nh35_21600``).

    PLATFORMIO_BUILD_FLAGS=-DTG_SYNTH_CLIP=nh35_21600 pio run -e pico2w_synthetic -t upload

The header is rewritten only when the clip changes, so incremental builds stay
incremental. Does nothing when the flag is absent.
"""
import os
import re
import shlex
import struct
import wave

Import("env")  # noqa: F821 (provided by PlatformIO / SCons)


def _requested_clip(environment):
    """The TG_SYNTH_CLIP value from build_flags or PLATFORMIO_BUILD_FLAGS, or None."""
    flags = []
    try:
        flags += environment.GetProjectOption("build_flags").split("\n")
    except Exception:  # noqa: BLE001 (option absent)
        pass
    flags.append(os.environ.get("PLATFORMIO_BUILD_FLAGS", ""))
    found = None
    for chunk in flags:
        for tok in shlex.split(chunk, comments=True):
            m = re.fullmatch(r"-DTG_SYNTH_CLIP=([A-Za-z0-9_]+)", tok)
            if m:
                found = m.group(1)
    return found


def _write_header(wav_path, header_path, clip_id):
    with wave.open(wav_path, "rb") as w:
        if w.getnchannels() != 1 or w.getsampwidth() != 2 or w.getframerate() != 48000:
            raise SystemExit(f"{wav_path}: need mono S16 at 48 kHz")
        n = w.getnframes()
        samples = struct.unpack("<" + "h" * n, w.readframes(n))
    lines = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"/* Generated by scripts/synth_clip_header.py from assets/synth_clips/{clip_id}.wav",
        " * (mono S16 @ 48 kHz). Do not edit; see assets/synth_clips/README.md. */",
        f"#define TICK_TOCK_PCM_LEN {n}u",
        "#define TICK_TOCK_PCM_RATE_HZ 48000u",
        "",
        "static const int16_t kTickTockPcm[TICK_TOCK_PCM_LEN] = {",
    ]
    for i in range(0, n, 16):
        lines.append("  " + ",".join(str(v) for v in samples[i:i + 16]) + ",")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    if os.path.exists(header_path) and open(header_path).read() == text:
        return
    with open(header_path, "w") as f:
        f.write(text)


clip = _requested_clip(env)  # noqa: F821
if clip is not None:
    root = env.subst("$PROJECT_DIR")  # noqa: F821
    wav_path = os.path.join(root, "assets", "synth_clips", clip + ".wav")
    if not os.path.isfile(wav_path):
        known = sorted(f[:-4] for f in os.listdir(os.path.join(root, "assets", "synth_clips")) if f.endswith(".wav"))
        raise SystemExit(f"TG_SYNTH_CLIP={clip}: no {wav_path}. Known clips: {', '.join(known)}")
    out_dir = os.path.join(env.subst("$BUILD_DIR"), "synth_clip")  # noqa: F821
    os.makedirs(out_dir, exist_ok=True)
    _write_header(wav_path, os.path.join(out_dir, "synth_clip_pcm.h"), clip)
    env.Append(CPPPATH=[out_dir])  # noqa: F821
    env.Append(CPPDEFINES=[("TG_SYNTH_CLIP_NAME", '\\"%s\\"' % clip)])  # noqa: F821
    print(f"synth_clip_header: TG_SYNTH_CLIP={clip} ({wav_path})")
